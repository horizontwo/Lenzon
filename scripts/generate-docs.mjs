// @ts-check

// Writes the two generated parts of the writing kit, from the code itself.
//
// - TEMPLATES.md, the template catalog, from the registry.
// - The worked example at the end of WRITING-SCRIPTS.md, from the `idea`
//   sample script. The rest of the guide is written by hand.
// - dist/templates.json, each template id and its `use`. The command reads
//   it to check a script's template names, since it cannot import the
//   player itself.
//
// Both are generated so they cannot drift from the code. The producer's
// hand-written catalog in Lenzon's server already showed how a copy drifts.
//
// The registry is loaded through Vite rather than plain Node, because the
// templates are TypeScript and import CSS, and the player's prismjs import
// has no extension, which plain Node refuses. Vite is already a dev
// dependency, so this adds nothing to install.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CATALOG = fileURLToPath(new URL('../TEMPLATES.md', import.meta.url));
const GUIDE = fileURLToPath(new URL('../WRITING-SCRIPTS.md', import.meta.url));
const DIST = fileURLToPath(new URL('../dist/', import.meta.url));

/**
 * The registry fields this script reads. Written out here rather than
 * imported, because importing the registry's own type would typecheck the
 * whole browser player under this Node-only config.
 *
 * @typedef {{
 *   id: string,
 *   description: string,
 *   use: 'any' | 'code',
 *   slots?: Record<string, string>,
 *   emphasizeTargets?: string,
 *   demo?: { content: Record<string, unknown>, emphasizeAfter?: { target: string } },
 * }} Template
 */

const server = await createServer({
  root: ROOT,
  configFile: false,
  logLevel: 'error',
  server: { middlewareMode: true },
  appType: 'custom',
});

/** @type {Template[]} */
let templates;
/** @type {import('@lenzon/explainer-format').PresentationScript} */
let example;
try {
  const registry = await server.ssrLoadModule('/src/templates/index.ts');
  templates = registry.listTemplates();
  example = (await server.ssrLoadModule('/src/player/samples/index.ts')).sampleScripts.idea;
} finally {
  await server.close();
}

const byId = (/** @type {{ id: string }} */ a, /** @type {{ id: string }} */ b) => a.id.localeCompare(b.id);
const anyIdea = templates.filter((t) => t.use === 'any').sort(byId);
const codeOnly = templates.filter((t) => t.use === 'code').sort(byId);

/** The first sentence of a description, for the index. */
const firstSentence = (/** @type {string} */ text) => (/^.*?[.!?](?=\s|$)/.exec(text)?.[0] ?? text).trim();

/**
 * JSON that keeps any object or array on one line when it fits. Fully
 * indented demos tripled the file's length, which costs an agent reading it.
 *
 * @param {unknown} value
 * @param {string} indent
 * @returns {string}
 */
function compactJson(value, indent = '') {
  const flat = JSON.stringify(value);
  if (value === null || typeof value !== 'object' || indent.length + flat.length <= 76) return flat;
  const inner = indent + '  ';
  const items = Array.isArray(value)
    ? value.map((v) => inner + compactJson(v, inner))
    : Object.entries(value).map(([k, v]) => `${inner}${JSON.stringify(k)}: ${compactJson(v, inner)}`);
  const [open, close] = Array.isArray(value) ? ['[', ']'] : ['{', '}'];
  return `${open}\n${items.join(',\n')}\n${indent}${close}`;
}

/** @param {Template} t */
function entry(t) {
  const lines = [`### ${t.id}`, '', t.description, ''];
  const slots = Object.entries(t.slots ?? {});
  if (slots.length) {
    lines.push('Content slots:', '');
    for (const [name, text] of slots) lines.push(`- \`${name}\`: ${text}`);
    lines.push('');
  }
  if (t.emphasizeTargets) lines.push(`Emphasize target: ${t.emphasizeTargets}.`, '');
  if (t.demo) {
    lines.push(
      'Example `primitive`:',
      '',
      '```json',
      compactJson({ template: t.id, content: t.demo.content }),
      '```',
      '',
    );
    if (t.demo.emphasizeAfter) {
      const beat = { at: 2, action: { type: 'emphasize', target: t.demo.emphasizeAfter.target } };
      lines.push(`Example beat: \`${JSON.stringify(beat)}\``, '');
    }
  }
  return lines.join('\n');
}

/** @param {Template[]} list */
const index = (list) => list.map((t) => `- [\`${t.id}\`](#${t.id}): ${firstSentence(t.description)}`).join('\n');

const doc = `# Template catalog

<!-- Generated by scripts/generate-docs.mjs from the template registry. Do not edit by hand. -->

Every scene names one template in \`primitive.template\` and fills its
slots in \`primitive.content\`. These are the ${templates.length} templates
that ship with \`@lenzon/player\`, version-matched to this package.

The first ${anyIdea.length} suit any idea: a business plan, a process, a
concept. The other ${codeOnly.length} only make sense for software, such as
a diff or a pull request.

Slots marked optional, or with a default, can be left out. A beat's
\`emphasize\` target is different for each template, so each entry says
what it takes.

For how to write a good script, read \`WRITING-SCRIPTS.md\` beside this file.

## For any idea

${index(anyIdea)}

## For code

${index(codeOnly)}

## For any idea, in detail

${anyIdea.map(entry).join('\n')}
## For code, in detail

${codeOnly.map(entry).join('\n')}`;

writeFileSync(CATALOG, doc);

// The guide promises its example uses only templates for any idea. Hold it
// to that here, so a later edit to the sample cannot quietly break it.
const useOf = new Map(templates.map((t) => [t.id, t.use]));
for (const scene of example.scenes) {
  const use = useOf.get(scene.primitive.template);
  if (use !== 'any') {
    throw new Error(`the idea sample's scene "${scene.id}" uses ${scene.primitive.template}, which is ${use ? `marked '${use}'` : 'not a template'}`);
  }
}

const BEGIN = '<!-- example:begin -->';
const END = '<!-- example:end -->';
const guide = readFileSync(GUIDE, 'utf8');
const start = guide.indexOf(BEGIN);
const end = guide.indexOf(END);
if (start < 0 || end < start) throw new Error(`WRITING-SCRIPTS.md has lost its ${BEGIN} and ${END} markers`);
const block = `${BEGIN}\n\n\`\`\`json\n${compactJson(example)}\n\`\`\`\n\n`;
writeFileSync(GUIDE, guide.slice(0, start) + block + guide.slice(end));

mkdirSync(DIST, { recursive: true });
writeFileSync(
  `${DIST}templates.json`,
  JSON.stringify(Object.fromEntries([...anyIdea, ...codeOnly].map((t) => [t.id, { use: t.use }])), null, 2) + '\n',
);

process.stdout.write(`generate-docs: ${templates.length} templates in TEMPLATES.md and dist/templates.json, and the example in WRITING-SCRIPTS.md\n`);
